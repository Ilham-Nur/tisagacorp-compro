const header = document.querySelector(".site-header");
const toggle = document.querySelector(".language-toggle");
const menuToggle = document.querySelector(".menu-toggle");

function updateHeader() {
  if (!header) return;
  const shouldUseSolidHeader = window.scrollY > 24 || header.classList.contains("page-header");
  header.classList.toggle("is-scrolled", shouldUseSolidHeader);
}

function getInitialLanguage() {
  const stored = localStorage.getItem("tle-language");
  return stored === "en" || stored === "id" ? stored : "id";
}

function applyLanguage(lang) {
  const dictionary = translations[lang] || translations.id;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });
  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    const key = node.dataset.i18nHtml;
    if (dictionary[key]) {
      node.innerHTML = dictionary[key];
    }
  });
  document.querySelectorAll("[data-lang-option]").forEach((node) => {
    node.classList.toggle("is-active", node.dataset.langOption === lang);
  });

  const page = document.body.dataset.page || "home";
  const titleMap = {
    group: "pageTitleGroup",
    home: "pageTitleHome",
    tle: "pageTitleTle",
    rivesa: "pageTitleRivesa",
    "rivesa-organization": "pageTitleRivesaOrganization",
    product: "pageTitleProduct",
    organization: "pageTitleOrganization",
  };
  const titleKey = titleMap[page] || "pageTitleHome";
  document.title = dictionary[titleKey];
  localStorage.setItem("tle-language", lang);
  scheduleWorkProcessPath();
}

function updateWorkProcessPath() {
  const wrapper = document.querySelector(".work-process-wrap");
  const svg = wrapper?.querySelector(".work-process-line");
  const path = wrapper?.querySelector(".work-process-path");
  const items = wrapper ? [...wrapper.querySelectorAll(".work-process li")] : [];

  if (!wrapper || !svg || !path || items.length < 2) return;

  const wrapperRect = wrapper.getBoundingClientRect();
  const steps = items.map((item) => {
    const rect = item.getBoundingClientRect();
    const even = (items.indexOf(item) + 1) % 2 === 0;
    return {
      top: rect.top - wrapperRect.top,
      bottom: rect.bottom - wrapperRect.top,
      x: rect.left - wrapperRect.left + (even ? rect.width - 42 : 42),
      y: rect.top - wrapperRect.top + rect.height / 2,
    };
  });

  svg.setAttribute("viewBox", `0 0 ${wrapperRect.width} ${wrapperRect.height}`);
  svg.setAttribute("preserveAspectRatio", "none");

  const curve = (from, to) => {
    const dx = to.x - from.x;
    const direction = dx >= 0 ? 1 : -1;
    const radius = 24;
    const gapY = from.bottom + (to.top - from.bottom) / 2;
    return [
      ` L ${from.x} ${gapY - radius}`,
      ` Q ${from.x} ${gapY}, ${from.x + direction * radius} ${gapY}`,
      ` L ${to.x - direction * radius} ${gapY}`,
      ` Q ${to.x} ${gapY}, ${to.x} ${gapY + radius}`,
      ` L ${to.x} ${to.y}`,
    ].join("");
  };

  let d = `M ${steps[0].x} ${steps[0].y}`;
  steps.slice(1).forEach((point, index) => {
    d += curve(steps[index], point);
  });

  path.setAttribute("d", d);
}

function scheduleWorkProcessPath() {
  window.requestAnimationFrame(updateWorkProcessPath);
}

toggle?.addEventListener("click", () => {
  const current = localStorage.getItem("tle-language") || "id";
  applyLanguage(current === "id" ? "en" : "id");
});

menuToggle?.addEventListener("click", () => {
  const isOpen = header?.classList.toggle("menu-open") || false;
  menuToggle.setAttribute("aria-expanded", String(isOpen));
});

header?.querySelectorAll(".main-nav a, .header-actions a").forEach((link) => {
  link.addEventListener("click", () => {
    header.classList.remove("menu-open");
    menuToggle?.setAttribute("aria-expanded", "false");
  });
});

window.addEventListener("resize", () => {
  if (window.innerWidth > 980) {
    header?.classList.remove("menu-open");
    menuToggle?.setAttribute("aria-expanded", "false");
  }
});

window.addEventListener("scroll", updateHeader, { passive: true });
window.addEventListener("resize", scheduleWorkProcessPath);
window.addEventListener("load", scheduleWorkProcessPath);
applyLanguage(getInitialLanguage());
updateHeader();
scheduleWorkProcessPath();
